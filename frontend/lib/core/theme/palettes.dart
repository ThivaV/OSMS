/// A selectable theme: one palette in a light and a dark version. Names are
/// our own; none reuse another reader's theme names.
class Palette {
  const Palette({
    required this.id,
    required this.name,
    required this.description,
    required this.light,
    required this.dark,
  });

  final String id;
  final String name;
  final String description;
  final OsmsColors light;
  final OsmsColors dark;

  OsmsColors forBrightness(Brightness brightness) => brightness == Brightness.dark ? dark : light;
}

